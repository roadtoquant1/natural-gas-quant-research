"""Release-date and price-alignment tests, including explicit no-look-ahead checks.

All prices and storage numbers here are SYNTHETIC (hand-made or generated by
tests/synthetic_data.py) and exist only to test the code.
"""

import numpy as np
import pandas as pd
import pytest

from natgas_quant import release_calendar as RC
from natgas_quant.dataset import build_event_table

from synthetic_data import make_test_config, synthetic_prices, synthetic_storage

T = pd.Timestamp


def _hol(a="2023-01-01", b="2027-01-01"):
    return RC.federal_holidays(a, b)


# ---------------------------------------------------------------------------
# Release dates
# ---------------------------------------------------------------------------
def test_normal_week_releases_on_thursday():
    rel, src, unc, _ = RC.rule_based_release(T("2024-03-01"), _hol())
    assert rel == T("2024-03-07") and rel.day_name() == "Thursday"
    assert src == "rule_nominal" and not unc


def test_monday_holiday_does_not_shift_release():
    # Labor Day 2024 = Monday 2 Sep; week ending Fri 30 Aug
    rel, src, unc, _ = RC.rule_based_release(T("2024-08-30"), _hol())
    assert rel == T("2024-09-05") and not unc


def test_midweek_holiday_assumes_later_release_and_flags():
    # Juneteenth 2024 = Wednesday 19 Jun; nominal Thursday 20 Jun
    rel, src, unc, note = RC.rule_based_release(T("2024-06-14"), _hol())
    assert rel == T("2024-06-21") and unc
    assert src == "rule_holiday_assume_later"


def test_thanksgiving_assumes_friday():
    rel, _, unc, _ = RC.rule_based_release(T("2024-11-22"), _hol())
    assert rel == T("2024-11-29") and unc


def test_year_end_window_is_flagged_without_shift():
    rel, src, unc, _ = RC.rule_based_release(T("2023-12-15"), _hol())  # nominal Thu 21 Dec
    assert rel == T("2023-12-21") and unc and src == "rule_nominal"


def test_verified_dates_override_rules():
    verified = pd.DataFrame({
        "storage_week_ending_date": [T("2025-12-19")],
        "report_release_date": [T("2025-12-29")],
        "report_release_time_et": ["12:00"],
    })
    cal = RC.build_release_calendar([T("2025-12-12"), T("2025-12-19")], verified)
    row = cal.set_index("storage_week_ending_date").loc[T("2025-12-19")]
    assert row["report_release_date"] == T("2025-12-29")
    assert row["release_date_source"] == "verified_schedule"
    assert row["report_release_timestamp_et"] == "2025-12-29 12:00"


def test_repository_verified_file_loads_and_is_consistent():
    from natgas_quant.config import PROJECT_ROOT

    v = RC.load_verified_releases(PROJECT_ROOT / "data/raw/manual/eia_wngsr_verified_release_dates.csv")
    assert len(v) >= 9
    assert (v["storage_week_ending_date"].dt.dayofweek == 4).all()
    gap = (v["report_release_date"] - v["storage_week_ending_date"]).dt.days
    assert gap.between(5, 10).all()


# ---------------------------------------------------------------------------
# Price alignment on a hand-built week
# ---------------------------------------------------------------------------
def _cal(release):
    return pd.DataFrame({"storage_week_ending_date": [T(release) - pd.Timedelta(days=6)],
                         "report_release_date": [T(release)]})


def test_entry_is_first_price_strictly_after_release_day():
    # Release Thursday 2024-03-07. Prices exist Wed, Thu, Fri, Mon.
    pdates = pd.DatetimeIndex(["2024-03-06", "2024-03-07", "2024-03-08", "2024-03-11"])
    al = RC.align_releases_to_prices(_cal("2024-03-07"), pdates, entry_lag_trading_days=1)
    r = al.iloc[0]
    assert r["price_before_release_date"] == T("2024-03-06")       # Wednesday
    assert r["first_eligible_price_date"] == T("2024-03-08")       # Friday, NOT Thursday
    assert r["alignment_ok"]
    al2 = RC.align_releases_to_prices(_cal("2024-03-07"), pdates, entry_lag_trading_days=2)
    assert al2.iloc[0]["first_eligible_price_date"] == T("2024-03-11")


def test_missing_friday_price_moves_entry_to_next_valid_day():
    pdates = pd.DatetimeIndex(["2024-03-06", "2024-03-07", "2024-03-11"])  # Friday missing
    al = RC.align_releases_to_prices(_cal("2024-03-07"), pdates)
    assert al.iloc[0]["first_eligible_price_date"] == T("2024-03-11")


def test_long_price_gap_marks_week_unusable():
    pdates = pd.DatetimeIndex(["2024-03-06", "2024-03-20"])
    al = RC.align_releases_to_prices(_cal("2024-03-07"), pdates, max_entry_gap_calendar_days=7)
    assert not al.iloc[0]["alignment_ok"]


def test_entry_lag_zero_is_rejected():
    with pytest.raises(ValueError):
        RC.align_releases_to_prices(_cal("2024-03-07"), pd.DatetimeIndex(["2024-03-08"]), 0)


def test_assert_no_lookahead_catches_bad_rows():
    bad = pd.DataFrame({
        "storage_week_ending_date": [T("2024-03-01")],
        "report_release_date": [T("2024-03-07")],
        "price_before_release_date": [T("2024-03-06")],
        "first_eligible_price_date": [T("2024-03-07")],   # same day as release: forbidden
        "alignment_ok": [True],
    })
    with pytest.raises(AssertionError):
        RC.assert_no_lookahead(bad)


# ---------------------------------------------------------------------------
# End-to-end no-look-ahead check on the synthetic pipeline
# ---------------------------------------------------------------------------
FEATURE_COLS = ["z", "anomaly_bcf", "expected_change_bcf", "z_lag1", "prior_ret_1d",
                "prior_ret_5d", "trailing_vol_20d", "withdrawal_season", "month"]


def test_future_data_cannot_change_past_features():
    cfg = make_test_config()
    st, px = synthetic_storage(), synthetic_prices()
    ev, _, _ = build_event_table(st, px, None, cfg)
    ok = ev[ev["z"].notna() & ev["alignment_ok"]]
    target_row = ok.iloc[len(ok) // 2]
    rel = target_row["report_release_date"]
    we = target_row["storage_week_ending_date"]

    # Corrupt EVERYTHING the public could not have known at decision time:
    # prices dated on/after the release day, and storage for later weeks.
    px2 = px.copy()
    px2.loc[px2["date"] >= rel, "price"] *= 7.0
    st2 = st.copy()
    st2.loc[st2["week_ending_date"] > we, "storage_level_bcf"] += 9999.0
    ev2, _, _ = build_event_table(st2, px2, None, cfg)

    a = ev.set_index("storage_week_ending_date").loc[we, FEATURE_COLS]
    b = ev2.set_index("storage_week_ending_date").loc[we, FEATURE_COLS]
    pd.testing.assert_series_equal(a.astype(float), b.astype(float), check_names=False)
    # ...while the forward target (which SHOULD use the future) does change.
    ta = ev.set_index("storage_week_ending_date").loc[we, "price_after_release"]
    tb = ev2.set_index("storage_week_ending_date").loc[we, "price_after_release"]
    assert tb == pytest.approx(7.0 * ta)


def test_every_aligned_entry_follows_its_release():
    ev, _, _ = build_event_table(synthetic_storage(), synthetic_prices(), None, make_test_config())
    ok = ev[ev["alignment_ok"]]
    assert (ok["first_eligible_price_date"] > ok["report_release_date"]).all()
    assert (ok["price_before_release_date"] < ok["report_release_date"]).all()
    assert (ok["report_release_date"] > ok["storage_week_ending_date"]).all()
    # holiday weeks are present and flagged in the synthetic sample
    assert ev["release_date_uncertain"].any()


def test_alignment_table_has_requested_columns():
    from natgas_quant.dataset import alignment_table

    ev, _, _ = build_event_table(synthetic_storage(), synthetic_prices(), None, make_test_config())
    tab = alignment_table(ev)
    for col in ["storage_week_ending_date", "report_release_date", "report_release_timestamp_et",
                "storage_level_bcf", "storage_change_bcf", "first_eligible_price_date", "price_before_release",
                "price_after_release", "one_day_forward_return", "three_day_forward_return",
                "five_day_forward_return"]:
        assert col in tab.columns, col
